CREATE TABLE IF NOT EXISTS crawler_training.search_keywords (
 keyword_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 keyword text NOT NULL CHECK (length(keyword) BETWEEN 1 AND 100 AND keyword = btrim(keyword)),
 normalized_keyword text NOT NULL UNIQUE CHECK (length(normalized_keyword) BETWEEN 1 AND 100),
 enabled boolean NOT NULL DEFAULT true,
 priority integer NOT NULL DEFAULT 100 CHECK (priority BETWEEN 1 AND 9999),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 deleted_at timestamptz,
 CHECK (deleted_at IS NULL OR enabled=false)
);
CREATE TABLE IF NOT EXISTS crawler_training.keyword_jobs (
 job_id uuid PRIMARY KEY,
 keyword_id bigint NOT NULL REFERENCES crawler_training.search_keywords(keyword_id),
 run_id uuid REFERENCES crawler_training.runs(run_id),
 status text NOT NULL DEFAULT 'PENDING'
  CHECK (status IN ('PENDING','RUNNING','FETCHED','FAILED','COMPLETED','CANCELLED')),
 idempotency_key text NOT NULL UNIQUE CHECK (length(idempotency_key) BETWEEN 1 AND 200),
 created_at timestamptz NOT NULL DEFAULT now(),
 started_at timestamptz,
 ended_at timestamptz,
 error_code text,
 CHECK (ended_at IS NULL OR status IN ('FAILED','COMPLETED','CANCELLED'))
);
CREATE INDEX IF NOT EXISTS t151_keyword_jobs_keyword_status_idx
 ON crawler_training.keyword_jobs(keyword_id,status,created_at DESC);
CREATE TABLE IF NOT EXISTS crawler_training.keyword_posting_discoveries (
 keyword_id bigint NOT NULL REFERENCES crawler_training.search_keywords(keyword_id),
 source_code text NOT NULL,
 external_posting_id text NOT NULL,
 first_seen_at timestamptz NOT NULL DEFAULT now(),
 last_seen_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY (keyword_id,source_code,external_posting_id),
 FOREIGN KEY (source_code,external_posting_id)
  REFERENCES crawler_training.postings(source_code,external_posting_id)
);
CREATE INDEX IF NOT EXISTS t151_discoveries_posting_idx
 ON crawler_training.keyword_posting_discoveries(source_code,external_posting_id);

